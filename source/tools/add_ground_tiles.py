#!/usr/bin/env python3
"""Add the original ground tile layout to the converted maps.

Usage: tools/add_ground_tiles.py <path/to/OpenSA/mods/sa> [--maps assets/data/maps] [--data assets/data]

The OpenSA maps store, for every cell, a terrain template id and the quarter of that template
(the original's 48x48 tiles cover 2x2 cells). This script copies that layout, cropped to the
same bounds as tools/convert_opensa_maps.py, into each converted map as

    tiles: Some("TTQTTQ...\\n..."),   // per cell: template id (2 hex digits) + quarter (1 hex digit)

and writes assets/data/tilesets.ron, the template id -> Game.DDF image name table of the four
tilesets. Only ids and names are copied: the tile pictures are read from the player's own copy of
Swarm Assault at run time (see crates/sa_game/src/original.rs).
"""
import os
import re
import struct
import sys

ARGS = sys.argv[1:]
if not ARGS or ARGS[0].startswith("-"):
    sys.exit(__doc__)
MOD = ARGS[0]
MAPS = "assets/data/maps"
DATA = "assets/data"
i = 1
while i < len(ARGS):
    if ARGS[i] == "--maps":
        MAPS = ARGS[i + 1]
        i += 2
    elif ARGS[i] == "--data":
        DATA = ARGS[i + 1]
        i += 2
    else:
        i += 1

TILESETS = ("normal", "desert", "swamp", "candy")


def parse_templates(name):
    text = open(os.path.join(MOD, "tilesets", f"{name}.yaml"), encoding="utf-8").read()
    out = {}
    for m in re.finditer(r"Template@(\d+):\s*\n\s*Id:\s*(\d+)\s*\n\s*Images:\s*sprites\|([A-Z0-9_]+)\.DDF", text):
        out[int(m.group(2))] = m.group(3)
    return out


def parse_bin(path):
    d = open(path, "rb").read()
    w, h = struct.unpack("<HH", d[1:5])
    tiles = [struct.unpack("<HB", d[5 + 3 * i:8 + 3 * i]) for i in range(w * h)]
    return w, h, tiles  # column-major: index = x * h + y


templates = {t: parse_templates(t) for t in TILESETS}
lines = ["// Ground tile templates of the four tilesets: template id -> image in the original Game.DDF.",
         "// Generated by tools/add_ground_tiles.py from the OpenSA tileset definitions.", "{"]
for t in TILESETS:
    lines.append(f'    "{t}": {{')
    for tid in sorted(templates[t]):
        lines.append(f'        {tid}: "{templates[t][tid]}",')
    lines.append("    },")
lines.append("}")
with open(os.path.join(DATA, "tilesets.ron"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", os.path.join(DATA, "tilesets.ron"), {t: len(v) for t, v in templates.items()})

done = skipped = 0
for fname in sorted(os.listdir(MAPS)):
    if not fname.endswith(".ron"):
        continue
    path = os.path.join(MAPS, fname)
    text = open(path, encoding="utf-8").read()
    m = re.search(r"Converted from OpenSA mods/sa/maps/(\S+)", text)
    if not m:
        print(f"{fname:<44} not an OpenSA map: skipped")
        skipped += 1
        continue
    folder = os.path.join(MOD, "maps", m.group(1))
    if not os.path.exists(os.path.join(folder, "map.bin")):
        print(f"{fname:<44} OpenSA folder {m.group(1)} missing: skipped")
        skipped += 1
        continue
    y = open(os.path.join(folder, "map.yaml"), encoding="utf-8").read()
    tileset = re.search(r"^Tileset: (\w+)", y, re.M).group(1).lower()
    bx, by, bw, bh = [int(v) for v in re.search(r"^Bounds: (.*)$", y, re.M).group(1).split(",")]
    mw = int(re.search(r"^\s*width: (\d+),", text, re.M).group(1))
    mh = int(re.search(r"^\s*height: (\d+),", text, re.M).group(1))
    if (mw, mh) != (bw, bh):
        print(f"{fname:<44} size {mw}x{mh} != OpenSA bounds {bw}x{bh}: skipped")
        skipped += 1
        continue
    w, h, tiles = parse_bin(os.path.join(folder, "map.bin"))
    known = templates[tileset]
    rows = []
    unknown = 0
    for yy in range(by, by + bh):
        row = []
        for xx in range(bx, bx + bw):
            tid, q = tiles[xx * h + yy]
            if tid not in known:
                unknown += 1
            row.append(f"{tid & 0xff:02x}{q & 0xf:x}")
        rows.append("".join(row))
    line = '    tiles: Some("' + "\\n".join(rows) + '"),'
    comment = "    // original ground: per cell the tileset template id (2 hex digits) and its quarter (1 hex digit)"
    text = re.sub(r"\n    // original ground:[^\n]*\n    tiles: Some\(\"[^\"]*\"\),", "", text)
    idx = text.rstrip().rfind(")")
    text = text[:idx].rstrip("\n") + "\n" + comment + "\n" + line + "\n)\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    done += 1
    print(f"{fname:<44} {tileset:<7} {bw}x{bh} unknown-templates {unknown}")
print(f"{done} maps updated, {skipped} skipped")
